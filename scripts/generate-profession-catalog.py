#!/usr/bin/env python3
"""Generate Classic profession item-ID lists from an AtlasLoot Classic data snapshot and catalog/skinning.json."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
NAMES = {1: "First Aid", 2: "Blacksmithing", 3: "Leatherworking", 4: "Alchemy",
         5: "Herbalism", 11: "Fishing", 12: "Skinning", 14: "Jewelcrafting", 15: "Inscription",
         6: "Cooking", 7: "Mining", 8: "Tailoring", 9: "Engineering", 10: "Enchanting", 13: "Poisons"}


def classic(text, table):
    return text.split(table + ".CLASSIC = {", 1)[1].split("\n}", 1)[0]


def generate(folder):
    sources = {name: (folder / name).read_bytes() for name in ("Profession.lua", "Recipe.lua")}
    professions = {p: {"id": name.lower().replace(" ", "-"), "name": name,
                        "materials": set(), "recipes": set(), "crafted": set()} for p, name in NAMES.items()}
    pattern = r"^\s*\[(\d+)\]\s*=\s*\{\s*(nil|\d+),\s*(\d+),[^{}]*\{([^{}]*)\}"
    for line in classic(sources["Profession.lua"].decode(), "PROFESSION_DATA").splitlines():
        if not re.match(r"^\s*\[\d+\]", line):
            continue
        match = re.match(pattern, line)
        if not match:
            raise ValueError("Unrecognized profession row: " + line)
        _, product, profession, ingredients = match.groups()
        entry = professions[int(profession)]
        entry["materials"].update(int(n) for n in re.findall(r"\d+", ingredients))
        if product != "nil" and int(product) > 0:
            entry["crafted"].add(int(product))
    crafted = set().union(*(p["crafted"] for p in professions.values()))
    for line in classic(sources["Recipe.lua"].decode(), "RECIPE_DATA").splitlines():
        if not re.match(r"^\s*\[\d+\]", line):
            continue
        match = re.match(r"^\s*\[(\d+)\]\s*=\s*\{\s*(\d+),", line)
        if not match:
            raise ValueError("Unrecognized recipe row: " + line)
        item, profession = map(int, match.groups())
        # AtlasLoot also indexes some finished goods for its profession tooltips.
        if item not in crafted:
            professions[profession]["recipes"].add(item)
    rows = sorted((p for p in professions.values() if any(p[k] for k in ("materials", "recipes", "crafted"))), key=lambda p: p["name"])
    if any(row["id"] == "skinning" for row in rows):
        raise ValueError("AtlasLoot now lists Skinning, which catalog/skinning.json would overwrite")
    for row in rows:
        for kind in ("materials", "recipes", "crafted"):
            row[kind] = sorted(row[kind])
    return {"game": "Classic", "source": "AtlasLoot Classic, Forever 1.60.1, Data/Profession.lua and Data/Recipe.lua",
            "sourceSha256": {name: hashlib.sha256(raw).hexdigest() for name, raw in sources.items()},
            "professions": rows}


def write_lua(catalog):
    lines = ["-- Generated by scripts/generate-profession-catalog.py. Do not edit.", "local _, ns = ...", "ns.ProfessionData = {"]
    for row in catalog["professions"]:
        lines.append('  { id = "%s", name = "%s",' % (row["id"], row["name"]))
        for kind in ("materials", "recipes", "crafted"):
            lines.append("    %s = { %s }," % (kind, ", ".join(map(str, row[kind]))))
        lines.append("  },")
    return "\n".join(lines + ["}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--atlasloot-data", type=Path, help="AtlasLootClassic/Data directory; omit to regenerate from the committed catalog and skinning.json")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "catalog/professions.json"
    catalog = generate(args.atlasloot_data) if args.atlasloot_data else json.loads(path.read_text())
    skinning = {"id": "skinning", "name": "Skinning",
                "materials": sorted(set(json.loads((ROOT / "catalog/skinning.json").read_text())["materials"])),
                "recipes": [], "crafted": []}
    catalog["professions"] = sorted([p for p in catalog["professions"] if p["id"] != "skinning"] + [skinning],
                                    key=lambda p: p["name"])
    rendered = json.dumps(catalog, indent=2)
    rendered = re.sub(r"\[\n([\d,\s]+)\n\s*\]", lambda m: "[" + ", ".join(re.findall(r"\d+", m[1])) + "]", rendered)
    outputs = {path: rendered + "\n", ROOT / "addon/Goldbook/ProfessionData.lua": write_lua(catalog)}
    for output, content in outputs.items():
        if args.check:
            assert output.read_text() == content, f"Regenerate {output.relative_to(ROOT)}"
        else:
            output.write_text(content)
    print("Verified" if args.check else "Generated", len(catalog["professions"]), "Classic profession lists.")


if __name__ == "__main__":
    main()
