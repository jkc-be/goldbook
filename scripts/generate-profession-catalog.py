#!/usr/bin/env python3
"""Generate Classic profession item-ID lists and recipe reagents from an AtlasLoot Classic data snapshot and the gathering lists in catalog/."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
NAMES = {1: "First Aid", 2: "Blacksmithing", 3: "Leatherworking", 4: "Alchemy",
         5: "Herbalism", 11: "Fishing", 12: "Skinning", 14: "Jewelcrafting", 15: "Inscription",
         6: "Cooking", 7: "Mining", 8: "Tailoring", 9: "Engineering", 10: "Enchanting", 13: "Poisons"}
GATHERING = ("Herbalism", "Skinning")
SOURCE = "AtlasLoot Classic, Forever 1.60.1, Data/Profession.lua and Data/Recipe.lua"
CRAFT = re.compile(r"\s*\[(\d+)\]\s*=\s*\{\s*(nil|\d+),\s*(\d+),\s*(\d+),\s*\d+,\s*\d+,"
                   r"\s*\{([\d,\s]*)\},\s*\{([\d,\s]*)\}(?:,\s*(\d+))?\s*\},\s*(?:--.*)?")
PROFESSIONS, CRAFTS = ROOT / "catalog/professions.json", ROOT / "catalog/crafts.json"


def classic(text, table):
    return text.split(table + ".CLASSIC = {", 1)[1].split("\n}", 1)[0]


def profession_id(number):
    return NAMES[number].lower().replace(" ", "-")


def parse_crafts(text):
    for line in classic(text, "PROFESSION_DATA").splitlines():
        if not re.match(r"^\s*\[\d+\]", line):
            continue
        match = CRAFT.fullmatch(line)
        if not match:
            raise ValueError("Unrecognized profession row: " + line)
        spell, item, profession, skill, reagents, counts, makes = match.groups()
        reagents, counts = (list(map(int, re.findall(r"\d+", group))) for group in (reagents, counts))
        if len(reagents) != len(counts):
            raise ValueError("Profession row lacks a count for each reagent: " + line)
        yield {"spell": int(spell), "item": None if item == "nil" else int(item), "profession": int(profession),
               "skill": int(skill), "makes": int(makes or 1), "reagents": list(zip(reagents, counts))}


def generate(folder):
    sources = {name: (folder / name).read_bytes() for name in ("Profession.lua", "Recipe.lua")}
    hashes = {name: hashlib.sha256(raw).hexdigest() for name, raw in sources.items()}
    crafts = sorted(parse_crafts(sources["Profession.lua"].decode()), key=lambda craft: craft["spell"])
    professions = {p: {"id": profession_id(p), "name": name,
                        "materials": set(), "recipes": set(), "crafted": set()} for p, name in NAMES.items()}
    for craft in crafts:
        entry = professions[craft["profession"]]
        entry["materials"].update(item for item, _ in craft["reagents"])
        if craft["item"]:
            entry["crafted"].add(craft["item"])
    crafted = set().union(*(p["crafted"] for p in professions.values()))
    for line in classic(sources["Recipe.lua"].decode(), "RECIPE_DATA").splitlines():
        if not re.match(r"^\s*\[\d+\]", line):
            continue
        match = re.match(r"^\s*\[(\d+)\]\s*=\s*\{\s*(\d+),", line)
        if not match:
            raise ValueError("Unrecognized recipe row: " + line)
        item, profession = map(int, match.groups())
        # AtlasLoot also indexes some finished goods for its profession tooltips.
        if item not in crafted:
            professions[profession]["recipes"].add(item)
    rows = sorted((p for p in professions.values() if any(p[k] for k in ("materials", "recipes", "crafted"))), key=lambda p: p["name"])
    for row in rows:
        if row["name"] in GATHERING:
            raise ValueError(f"AtlasLoot now lists {row['name']}, which catalog/{row['id']}.json would overwrite")
        for kind in ("materials", "recipes", "crafted"):
            row[kind] = sorted(row[kind])
    recipes = [{**craft, "profession": profession_id(craft["profession"])} for craft in crafts if craft["item"]]
    return ({"game": "Classic", "source": SOURCE, "sourceSha256": hashes, "professions": rows},
            {"game": "Classic", "source": SOURCE, "sourceSha256": {"Profession.lua": hashes["Profession.lua"]}, "recipes": recipes})


def profession_json(catalog):
    rendered = json.dumps(catalog, indent=2)
    return re.sub(r"\[\n([\d,\s]+)\n\s*\]", lambda m: "[" + ", ".join(re.findall(r"\d+", m[1])) + "]", rendered) + "\n"


def profession_lua(catalog):
    lines = ["-- Generated by scripts/generate-profession-catalog.py. Do not edit.", "local _, ns = ...", "ns.ProfessionData = {"]
    for row in catalog["professions"]:
        lines.append('  { id = "%s", name = "%s",' % (row["id"], row["name"]))
        for kind in ("materials", "recipes", "crafted"):
            lines.append("    %s = { %s }," % (kind, ", ".join(map(str, row[kind]))))
        lines.append("  },")
    return "\n".join(lines + ["}", ""])


def craft_json(crafts):
    recipes = ",\n".join("    " + json.dumps(recipe) for recipe in crafts["recipes"])
    return json.dumps({**crafts, "recipes": []}, indent=2).replace('"recipes": []', f'"recipes": [\n{recipes}\n  ]') + "\n"


def craft_lua(crafts):
    lines = ["-- Generated by scripts/generate-profession-catalog.py. Do not edit.", "local _, ns = ...",
             "-- [spell] = { item, profession, skill (to learn it), makes (items per craft), reagents = { { item, count }, ... } }",
             "ns.CraftData = {"]
    for recipe in crafts["recipes"]:
        reagents = ", ".join(f"{{ {item}, {count} }}" for item, count in recipe["reagents"])
        lines.append(f'  [{recipe["spell"]}] = {{ item = {recipe["item"]}, profession = "{recipe["profession"]}", '
                     f'skill = {recipe["skill"]}, makes = {recipe["makes"]}, reagents = {{ {reagents} }} }},')
    return "\n".join(lines + ["}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--atlasloot-data", type=Path, help="AtlasLootClassic/Data directory; omit to regenerate from the committed catalogs and the gathering lists")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.atlasloot_data:
        catalog, crafts = generate(args.atlasloot_data)
    else:
        catalog, crafts = (json.loads(path.read_text()) for path in (PROFESSIONS, CRAFTS))
    gathering = [{"id": name.lower(), "name": name,
                  "materials": sorted(set(json.loads((ROOT / f"catalog/{name.lower()}.json").read_text())["materials"])),
                  "recipes": [], "crafted": []} for name in GATHERING]
    catalog["professions"] = sorted([p for p in catalog["professions"] if p["name"] not in GATHERING] + gathering,
                                    key=lambda p: p["name"])
    outputs = {PROFESSIONS: profession_json(catalog), ROOT / "addon/Goldbook/ProfessionData.lua": profession_lua(catalog),
               CRAFTS: craft_json(crafts), ROOT / "addon/Goldbook/CraftData.lua": craft_lua(crafts)}
    for output, content in outputs.items():
        if args.check:
            assert output.read_text() == content, f"Regenerate {output.relative_to(ROOT)}"
        else:
            output.write_text(content)
    print("Verified" if args.check else "Generated", len(catalog["professions"]), "Classic profession lists and",
          len(crafts["recipes"]), "recipes.")


if __name__ == "__main__":
    main()
